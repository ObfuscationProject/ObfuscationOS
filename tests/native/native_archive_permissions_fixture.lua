-- Included only by an explicit archive-only SDK consumer qualifier.
local archive_permissions_build = ok_user_builddir()

target("native-archive-permissions-probe")
    set_kind("binary")
    set_default(false)
    set_filename("native-archive-permissions-probe.elf")
    set_targetdir(path.join(archive_permissions_build, "fixtures"))
    add_deps("okcrt")
    add_ok_user_toolchain()
    add_ok_user_include_dirs()
    add_files(path.join(os.projectdir(), "tests/native/native_archive_permissions_probe.c"))
    local _, spec = ok_user_require_arch(ok_user_current_arch())
    add_files(path.join(os.projectdir(), "lib/okcrt/arch", spec.source, "crt0.S"))
    add_ok_user_cflags()
    add_ok_user_linkflags()
    add_syslinks("gcc")
target_end()

rule("ok.native.archive-permissions-stage")
    after_buildcmd(function (target, batchcmds)
        batchcmds:vrunv("python3", {"-B", path.join(os.projectdir(), "tests/native/stage_archive_permissions_fixture.py"),
            "--build", archive_permissions_build})
    end)
rule_end()
target("rootfs-stage")
    add_deps("native-archive-permissions-probe")
    add_rules("ok.native.archive-permissions-stage")
target_end()
