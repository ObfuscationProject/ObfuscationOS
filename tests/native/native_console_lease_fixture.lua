-- Included only by an explicit archive-only console lease SDK qualifier.
local console_lease_build = ok_user_builddir()
target("native-console-lease-probe")
    set_kind("binary")
    set_default(false)
    set_filename("native-console-lease-probe.elf")
    set_targetdir(path.join(console_lease_build, "fixtures"))
    add_deps("okcrt")
    add_ok_user_toolchain()
    add_ok_user_include_dirs()
    add_files(path.join(os.projectdir(), "tests/native/native_console_lease_probe.c"))
    local _, spec = ok_user_require_arch(ok_user_current_arch())
    add_files(path.join(os.projectdir(), "lib/okcrt/arch", spec.source, "crt0.S"))
    add_ok_user_cflags()
    add_ok_user_linkflags()
    add_syslinks("gcc")
target_end()
rule("ok.native.console-lease-stage")
    after_buildcmd(function (target, batchcmds)
        batchcmds:vrunv("python3", {"-B", path.join(os.projectdir(), "tests/native/stage_console_lease_fixture.py"),
            "--build", console_lease_build})
    end)
rule_end()
target("rootfs-stage")
    add_deps("native-console-lease-probe")
    add_rules("ok.native.console-lease-stage")
target_end()
