-- Explicit journalled-login qualification only; never included by the distro.
local login_fixture_build = ok_user_builddir()
target("native-login-session")
    set_kind("binary")
    set_default(false)
    set_filename("native-login-session.elf")
    set_targetdir(path.join(login_fixture_build, "fixtures"))
    add_deps("okcrt")
    add_ok_user_toolchain()
    add_ok_user_include_dirs()
    add_files(path.join(os.projectdir(), "tests/native/native_login_session.c"))
    local _, spec = ok_user_require_arch(ok_user_current_arch())
    add_files(path.join(os.projectdir(), "lib/okcrt/arch", spec.source, "crt0.S"))
    add_ok_user_cflags()
    add_ok_user_linkflags()
    add_syslinks("gcc")
target_end()
target("native-login-cut")
    set_kind("binary")
    set_default(false)
    set_filename("native-login-cut.elf")
    set_targetdir(path.join(login_fixture_build, "fixtures"))
    add_deps("okcrt")
    add_ok_user_toolchain()
    add_ok_user_include_dirs()
    add_includedirs(path.join(os.projectdir(), "apps/login"))
    add_files(path.join(os.projectdir(), "apps/login/*.c"))
    add_files(path.join(os.projectdir(), "tests/native/native_login_cut.c"))
    local _, spec = ok_user_require_arch(ok_user_current_arch())
    add_files(path.join(os.projectdir(), "lib/okcrt/arch", spec.source, "crt0.S"))
    add_ok_user_cflags()
    add_ok_user_linkflags()
    add_ldflags("-Wl,--wrap=renameat", {force = true})
    add_syslinks("gcc")
target_end()
rule("ok.native.login-stage")
    after_buildcmd(function (target, batchcmds)
        batchcmds:vrunv("python3", {"-B", path.join(os.projectdir(), "tests/native/stage_login_fixture.py"),
            "--build", login_fixture_build})
    end)
rule_end()
target("rootfs-stage")
    add_deps("app-login", "native-login-session", "native-login-cut")
    add_rules("ok.native.login-stage")
target_end()
